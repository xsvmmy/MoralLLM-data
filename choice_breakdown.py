"""choice_breakdown.py

For each model's 200-scenario nh (no human response) results, tally how
often the LLM chose STAY vs. SWERVE for every unique directional 1v1
scenario pair (e.g. "Man v. Woman" is distinct from "Woman v. Man" since
Scenario1_Description is the STAY-side group and Scenario2_Description is
the SWERVE-side group), broken down by the ethical framework the LLM cited
for each choice. All three rounds per model are aggregated together.

Two ways to invoke:
  python3 choice_breakdown.py [source_dir] [output_filename]
      Globs every *.csv in source_dir (default SOURCE_DIR) and writes the
      report there (default OUTPUT_FILENAME).
  python3 choice_breakdown.py file1.csv file2.csv ... [output_filename]
      Explicit CSV paths (any arg ending in .csv) instead of a directory
      glob — for files that don't live alongside only their own siblings.
      The report is written next to the first input file unless a trailing
      non-.csv arg gives an output filename.
"""

import csv
import glob
import os
import sys
from collections import Counter, defaultdict

SOURCE_DIR = "0824-1v1-nh-200-LLM-results"
OUTPUT_FILENAME = "nh-alph-1v1-200-choice-breakdown.txt"

# Raw Scenario{1,2}_Description strings (as generated by filter_responses.py)
# collapsed to the short labels used in the report.
LABEL_MAP = {
    "1 adult man/men (pedestrians)": "Man",
    "1 adult woman/women (pedestrians)": "Woman",
    "1 boy/boys (pedestrians)": "Boy",
    "1 girl/girls (pedestrians)": "Girl",
    "1 old man/men (pedestrians)": "Old Man",
    "1 old woman/women (pedestrians)": "Old Woman",
}


def short_label(raw_description):
    return LABEL_MAP.get(raw_description, raw_description)


def format_framework_counts(counter):
    return ", ".join(f"{framework}={count}" for framework, count in counter.most_common())


def main():
    script_dir = os.path.dirname(os.path.abspath(__file__))
    args = sys.argv[1:]
    explicit_csvs = [a for a in args if a.lower().endswith(".csv")]

    if explicit_csvs:
        csv_paths = sorted(
            a if os.path.isabs(a) else os.path.join(script_dir, a)
            for a in explicit_csvs
        )
        missing = [p for p in csv_paths if not os.path.exists(p)]
        if missing:
            sys.exit("Error: file(s) not found: " + ", ".join(missing))

        non_csv_args = [a for a in args if not a.lower().endswith(".csv")]
        output_filename = non_csv_args[0] if non_csv_args else OUTPUT_FILENAME
        output_dir = os.path.dirname(csv_paths[0]) or script_dir
    else:
        source_dir_arg = args[0] if len(args) > 0 else SOURCE_DIR
        output_filename = args[1] if len(args) > 1 else OUTPUT_FILENAME
        output_dir = os.path.join(script_dir, source_dir_arg)
        csv_paths = sorted(glob.glob(os.path.join(output_dir, "*.csv")))

    # model -> (s1_label, s2_label) -> choice ('STAY'/'SWERVE') -> EthicalFramework -> count
    data = defaultdict(lambda: defaultdict(lambda: defaultdict(Counter)))
    models_seen = []

    for csv_path in csv_paths:
        with open(csv_path, newline="", encoding="utf-8") as f:
            for row in csv.DictReader(f):
                choice = row["LLM_Judgment"]
                if choice not in ("STAY", "SWERVE"):
                    continue

                model = row["Model"]
                if model not in data:
                    models_seen.append(model)

                pair = (short_label(row["Scenario1_Description"]), short_label(row["Scenario2_Description"]))
                framework = row["EthicalFramework"]
                data[model][pair][choice][framework] += 1

    lines = []
    for model in sorted(models_seen):
        lines.append(f"Model: {model.capitalize()}")
        pairs = data[model]
        for (s1, s2) in sorted(pairs.keys()):
            choices = pairs[(s1, s2)]
            stay = choices.get("STAY", Counter())
            swerve = choices.get("SWERVE", Counter())
            stay_total = sum(stay.values())
            swerve_total = sum(swerve.values())
            lines.append(
                f"    {s1} v. {s2}: "
                f"STAY={stay_total} ({format_framework_counts(stay)}) "
                f"SWERVE={swerve_total} ({format_framework_counts(swerve)})"
            )
        lines.append("")

    output_path = os.path.join(output_dir, output_filename)
    with open(output_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines).rstrip() + "\n")

    print(f"Wrote breakdown for {len(models_seen)} models to: {output_path}")


if __name__ == "__main__":
    main()
